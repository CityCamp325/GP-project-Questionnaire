(function initializeTranslations() {
    const languageStorageKey = "dongMedicineLanguage";
    const originalText = new WeakMap();
    const originalAttributes = new WeakMap();

    function getTranslation(path) {
        return path.split(".").reduce((value, key) => value && value[key], window.translations.zh);
    }

    function applyLanguage(language) {
        window.siteLanguage = language;
        document.documentElement.lang = language === "zh" ? "zh-CN" : "en";

        document.querySelectorAll("[data-i18n]").forEach((element) => {
            if (!originalText.has(element)) {
                originalText.set(element, element.textContent);
            }
            const translation = language === "zh" ? getTranslation(element.dataset.i18n) : null;
            element.textContent = typeof translation === "string" ? translation : originalText.get(element);
        });

        document.querySelectorAll("[placeholder], [title], [aria-label]").forEach((element) => {
            if (!originalAttributes.has(element)) {
                originalAttributes.set(element, {});
            }
            ["placeholder", "title", "aria-label"].forEach((attribute) => {
                if (element.hasAttribute(attribute)) {
                    const attributes = originalAttributes.get(element);
                    if (!(attribute in attributes)) {
                        attributes[attribute] = element.getAttribute(attribute);
                    }
                    const localizedValue = element.getAttribute(`data-${attribute}-${language}`);
                    const translationKey = element.getAttribute(`data-${attribute}-i18n`);
                    const translatedValue = translationKey && getTranslation(translationKey);
                    if (language === "zh" && typeof translatedValue === "string") {
                        element.setAttribute(attribute, translatedValue);
                    } else if (localizedValue !== null) {
                        element.setAttribute(attribute, localizedValue);
                    } else {
                        element.setAttribute(attribute, attributes[attribute]);
                    }
                }
            });
        });

        document.querySelectorAll("[data-label-en], [data-label-zh], [data-label-i18n]").forEach((element) => {
            const translationKey = element.getAttribute("data-label-i18n");
            const translation = translationKey && getTranslation(translationKey);
            const label = language === "zh"
                ? (typeof translation === "string" ? translation : element.getAttribute("data-label-zh"))
                : element.getAttribute("data-label-en");
            if (label !== null) {
                element.textContent = label;
            }
        });

        const titleElement = document.querySelector("title");
        if (titleElement && !originalText.has(titleElement)) {
            originalText.set(titleElement, titleElement.textContent);
        }
        const pageTitle = titleElement?.getAttribute(`data-label-${language}`)
            || (titleElement?.dataset.i18n && getTranslation(titleElement.dataset.i18n));
        if (pageTitle) {
            document.title = language === "zh" ? pageTitle : originalText.get(titleElement);
        }

        const toggle = document.getElementById("languageToggle");
        if (toggle) {
            toggle.textContent = language === "en" ? "中文" : "English";
            toggle.setAttribute("aria-label", language === "en" ? "Switch to Chinese" : "切换为英文");
        }

        document.dispatchEvent(new Event("site-language-changed"));
    }

    window.getSiteTranslation = getTranslation;
    window.applySiteLanguage = applyLanguage;

    let savedLanguage = "en";
    try {
        savedLanguage = localStorage.getItem(languageStorageKey) || "en";
    } catch (error) {
        savedLanguage = "en";
    }
    applyLanguage(savedLanguage === "zh" ? "zh" : "en");

    const toggle = document.getElementById("languageToggle");
    if (toggle) {
        toggle.addEventListener("click", () => {
            const nextLanguage = window.siteLanguage === "en" ? "zh" : "en";
            try {
                localStorage.setItem(languageStorageKey, nextLanguage);
            } catch (error) {
                // Keep the current page switch working when storage is unavailable.
            }
            applyLanguage(nextLanguage);
        });
    }
})();
